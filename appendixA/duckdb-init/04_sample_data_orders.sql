           WHEN 7 THEN 'refunded'
           WHEN 13 THEN 'processing'
           WHEN 19 THEN 'shipped'
           WHEN 23 THEN 'pending'
           ELSE 'delivered'
       END
   )::order_status_enum
 WHERE order_id > 25;

